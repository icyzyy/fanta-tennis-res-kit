// Package texenc encodes images into FantaTennis .tex containers: a
// standard DDS (DXT1/DXT3/DXT5 block formats or uncompressed RGB24/RGBA32)
// with a full mip chain down to 1×1, obfuscated the way the game's loader
// expects: the 128-byte DDS header is byte-wise inverted, the pixel body
// is stored raw. It is the exact inverse of reskit's texdecoder — every
// header field it writes is one that adapter's parse() reads.
package texenc

import (
	"encoding/binary"
	"fmt"
	"image"
	"image/color"
	"image/draw"

	domain "github.com/icyzyy/fanta-tennis-res-kit/domain"
	usecase "github.com/icyzyy/fanta-tennis-res-kit/usecase"
)

const ddsHeaderSize = 128

type encoder struct{}

// New constructs a TextureEncoder port implementation.
func New() usecase.TextureEncoder {
	return &encoder{}
}

func (e *encoder) Encode(src image.Image, format domain.TextureFormat) ([]byte, error) {
	return Encode(src, format)
}

// Encode renders img as a .tex in the given format. The image is converted
// to NRGBA, a full mip chain is generated by box downsampling, each level
// is encoded, and the result is XOR-obfuscated.
func Encode(src image.Image, format domain.TextureFormat) ([]byte, error) {
	if src == nil {
		return nil, fmt.Errorf("texenc: nil image")
	}
	base := toNRGBA(src)
	w, h := base.Rect.Dx(), base.Rect.Dy()
	if w <= 0 || h <= 0 {
		return nil, fmt.Errorf("texenc: empty image %dx%d", w, h)
	}
	switch format {
	case domain.FmtDXT1, domain.FmtDXT3, domain.FmtDXT5,
		domain.FmtRGB24, domain.FmtRGBA32:
	default:
		return nil, fmt.Errorf("texenc: unsupported format %v", format)
	}

	levels := []*image.NRGBA{base}
	for l := levels[len(levels)-1]; l.Rect.Dx() > 1 || l.Rect.Dy() > 1; {
		l = downsample(l)
		levels = append(levels, l)
	}

	var body []byte
	for _, lvl := range levels {
		body = append(body, encodeLevel(lvl, format)...)
	}

	head := buildHeader(w, h, format, len(levels), levelSize(levels[0], format))
	out := append(head, body...)
	// The game's loader (FantaTennis.exe fcn.005DBC00) inverts only the
	// first 128 bytes (DDS header); the pixel body is used as stored.
	for i := 0; i < ddsHeaderSize; i++ {
		out[i] ^= 0xFF
	}
	return out, nil
}

// toNRGBA copies any image into a fresh 0-origin NRGBA.
func toNRGBA(src image.Image) *image.NRGBA {
	if n, ok := src.(*image.NRGBA); ok && n.Rect.Min.X == 0 && n.Rect.Min.Y == 0 {
		return n
	}
	b := src.Bounds()
	dst := image.NewNRGBA(image.Rect(0, 0, b.Dx(), b.Dy()))
	draw.Draw(dst, dst.Bounds(), src, b.Min, draw.Src)
	return dst
}

// downsample box-filters a level into the next mip (Direct3D floor halving).
func downsample(src *image.NRGBA) *image.NRGBA {
	w, h := src.Rect.Dx(), src.Rect.Dy()
	nw, nh := w/2, h/2
	if nw < 1 {
		nw = 1
	}
	if nh < 1 {
		nh = 1
	}
	dst := image.NewNRGBA(image.Rect(0, 0, nw, nh))
	for y := 0; y < nh; y++ {
		for x := 0; x < nw; x++ {
			var sr, sg, sb, sa, totalCount int
			for dy := 0; dy < 2; dy++ {
				for dx := 0; dx < 2; dx++ {
					sx, sy := x*2+dx, y*2+dy
					if sx >= w || sy >= h {
						continue
					}
					p := src.NRGBAAt(sx, sy)
					a := int(p.A)
					sr += int(p.R) * a
					sg += int(p.G) * a
					sb += int(p.B) * a
					sa += a
					totalCount++
				}
			}
			var r, g, b uint8
			if sa > 0 {
				r = uint8(sr / sa)
				g = uint8(sg / sa)
				b = uint8(sb / sa)
			}
			a := uint8(sa / totalCount)
			dst.SetNRGBA(x, y, color.NRGBA{R: r, G: g, B: b, A: a})
		}
	}
	return dst
}

// blockBytes returns the encoded size of one block for a format.
func blockBytes(format domain.TextureFormat) int {
	if format == domain.FmtDXT1 {
		return 8
	}
	return 16
}

// levelSize returns the encoded byte size of one mip level.
func levelSize(lvl *image.NRGBA, format domain.TextureFormat) int {
	w, h := lvl.Rect.Dx(), lvl.Rect.Dy()
	switch format {
	case domain.FmtDXT1, domain.FmtDXT3, domain.FmtDXT5:
		return ((w + 3) / 4) * ((h + 3) / 4) * blockBytes(format)
	case domain.FmtRGB24:
		return w * h * 3
	case domain.FmtRGBA32:
		return w * h * 4
	}
	return 0
}

// encodeLevel encodes one mip level's pixels.
func encodeLevel(lvl *image.NRGBA, format domain.TextureFormat) []byte {
	switch format {
	case domain.FmtDXT1, domain.FmtDXT3, domain.FmtDXT5:
		return encodeDXT(lvl, format)
	case domain.FmtRGB24, domain.FmtRGBA32:
		return encodeRaw(lvl, format)
	}
	return nil
}

// encodeRaw writes uncompressed pixels in the byte order the masks in the
// header describe: BGR (RGB24) or BGRA (RGBA32), little-endian.
func encodeRaw(lvl *image.NRGBA, format domain.TextureFormat) []byte {
	w, h := lvl.Rect.Dx(), lvl.Rect.Dy()
	withAlpha := format == domain.FmtRGBA32
	out := make([]byte, 0, w*h*(3+boolInt(withAlpha)))
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			p := lvl.NRGBAAt(x, y)
			out = append(out, p.B, p.G, p.R)
			if withAlpha {
				out = append(out, p.A)
			}
		}
	}
	return out
}

func boolInt(b bool) int {
	if b {
		return 1
	}
	return 0
}

// encodeDXT walks the level in 4×4 blocks; edge pixels are clamped, the
// same convention reskit's decoder uses for partial blocks.
func encodeDXT(lvl *image.NRGBA, format domain.TextureFormat) []byte {
	w, h := lvl.Rect.Dx(), lvl.Rect.Dy()
	bw, bh := (w+3)/4, (h+3)/4
	out := make([]byte, 0, bw*bh*blockBytes(format))
	var block [16]color.NRGBA
	for by := 0; by < bh; by++ {
		for bx := 0; bx < bw; bx++ {
			for py := 0; py < 4; py++ {
				for px := 0; px < 4; px++ {
					x, y := bx*4+px, by*4+py
					if x >= w {
						x = w - 1
					}
					if y >= h {
						y = h - 1
					}
					block[py*4+px] = lvl.NRGBAAt(x, y)
				}
			}
			switch format {
			case domain.FmtDXT1:
				out = append(out, encodeDXT1Block(block)...)
			case domain.FmtDXT3:
				out = append(out, encodeDXT3Block(block)...)
			case domain.FmtDXT5:
				out = append(out, encodeDXT5Block(block)...)
			}
		}
	}
	return out
}

// to565 quantizes to the 5-6-5 endpoint format with rounding.
func to565(c color.NRGBA) uint16 {
	r := (uint32(c.R)*31 + 127) / 255
	g := (uint32(c.G)*63 + 127) / 255
	b := (uint32(c.B)*31 + 127) / 255
	return uint16(r<<11 | g<<5 | b)
}

// expand565 converts a 565 endpoint to NRGBA with bit replication
// (identical to reskit's decoder so distances match what will be read back).
func expand565(c uint16) color.NRGBA {
	r := uint8((c >> 11) & 0x1F)
	g := uint8((c >> 5) & 0x3F)
	b := uint8(c & 0x1F)
	return color.NRGBA{R: r<<3 | r>>2, G: g<<2 | g>>4, B: b<<3 | b>>2, A: 255}
}

// mix interpolates two endpoints with integer weights (wa*a+wb*b)/div,
// mirroring reskit's decoder palette.
func mix(a, b color.NRGBA, wa, wb, div int) color.NRGBA {
	return color.NRGBA{
		R: uint8((wa*int(a.R) + wb*int(b.R)) / div),
		G: uint8((wa*int(a.G) + wb*int(b.G)) / div),
		B: uint8((wa*int(a.B) + wb*int(b.B)) / div),
		A: 255,
	}
}

// palette rebuilds the decoder's 4-entry palette for endpoint pair c0/c1.
func palette(c0, c1 uint16, fourColor bool) [4]color.NRGBA {
	p0, p1 := expand565(c0), expand565(c1)
	var pal [4]color.NRGBA
	pal[0], pal[1] = p0, p1
	if fourColor {
		pal[2] = mix(p0, p1, 2, 1, 3)
		pal[3] = mix(p0, p1, 1, 2, 3)
	} else {
		pal[2] = mix(p0, p1, 1, 1, 2)
		pal[3] = color.NRGBA{}
	}
	return pal
}

// pickEndpoints finds the two pixels in the block with the largest
// Euclidean distance in RGB space to serve as the line endpoints.
func pickEndpoints(block [16]color.NRGBA, opaqueOnly bool) (c0, c1 uint16) {
	var candidates []color.NRGBA
	for _, p := range block {
		if opaqueOnly && p.A < 128 {
			continue
		}
		candidates = append(candidates, p)
	}
	if len(candidates) == 0 {
		return 0, 0
	}
	bestP1, bestP2 := candidates[0], candidates[0]
	maxD := -1
	for i := 0; i < len(candidates); i++ {
		for j := i + 1; j < len(candidates); j++ {
			p1, p2 := candidates[i], candidates[j]
			dr := int(p1.R) - int(p2.R)
			dg := int(p1.G) - int(p2.G)
			db := int(p1.B) - int(p2.B)
			d := dr*dr + dg*dg + db*db
			if d > maxD {
				maxD = d
				bestP1, bestP2 = p1, p2
			}
		}
	}
	return to565(bestP1), to565(bestP2)
}

// nearestIndex picks the palette entry closest to p in RGB space.
func nearestIndex(p color.NRGBA, pal []color.NRGBA) int {
	best, bestD := 0, -1
	for i, c := range pal {
		dr, dg, db := int(p.R)-int(c.R), int(p.G)-int(c.G), int(p.B)-int(c.B)
		d := dr*dr + dg*dg + db*db
		if bestD < 0 || d < bestD {
			best, bestD = i, d
		}
	}
	return best
}

// packColors writes the 8-byte color half of a DXT block (endpoints +
// 2-bit indices, row-major, decoder order).
func packColors(c0, c1 uint16, idx [16]int) []byte {
	out := make([]byte, 8)
	binary.LittleEndian.PutUint16(out[0:2], c0)
	binary.LittleEndian.PutUint16(out[2:4], c1)
	var bits uint32
	for i, v := range idx {
		bits |= uint32(v&3) << (2 * i)
	}
	binary.LittleEndian.PutUint32(out[4:8], bits)
	return out
}

// encodeDXT1Block encodes one 4×4 block: opaque blocks use the 4-color
// mode (c0 > c1); blocks with transparency force the 3-color mode and
// map transparent pixels to index 3 (decoder reads that as transparent
// black — the order-based semantics the corpus was encoded with).
func encodeDXT1Block(block [16]color.NRGBA) []byte {
	hasAlpha := false
	for _, p := range block {
		if p.A < 128 {
			hasAlpha = true
			break
		}
	}
	var c0, c1 uint16
	var fourColor bool
	if hasAlpha {
		e0, e1 := pickEndpoints(block, true)
		if e0 > e1 {
			e0, e1 = e1, e0 // ensure c0 <= c1 for 3-color mode
		}
		c0, c1 = e0, e1
		fourColor = false
	} else {
		e0, e1 := pickEndpoints(block, false)
		if e0 < e1 {
			e0, e1 = e1, e0 // prefer c0 > c1 for 4-color mode
		}
		if e0 == e1 {
			// Solid color block: pick distinct endpoints to guarantee c0 > c1
			// while keeping all 16 pixels mapped to the exact color.
			var idx [16]int
			if e0 > 0 {
				c0, c1 = e0, 0
			} else {
				c0, c1 = 1, 0
				for i := range idx {
					idx[i] = 1 // index 1 is c1 (0 = black)
				}
			}
			return packColors(c0, c1, idx)
		}
		c0, c1 = e0, e1
		fourColor = true
	}
	pal := palette(c0, c1, fourColor)
	var idx [16]int
	for i, p := range block {
		if !fourColor && p.A < 128 {
			idx[i] = 3
			continue
		}
		limit := 4
		if !fourColor {
			limit = 3
		}
		idx[i] = nearestIndex(p, pal[:limit])
	}
	return packColors(c0, c1, idx)
}

// encodeDXT3Block: explicit 4-bit alpha + always-4-color block.
func encodeDXT3Block(block [16]color.NRGBA) []byte {
	out := make([]byte, 0, 16)
	out = append(out, encodeAlpha4(block)...)
	e0, e1 := pickEndpoints(block, false)
	if e0 < e1 {
		e0, e1 = e1, e0
	}
	c0, c1 := e0, e1
	pal := palette(c0, c1, true)
	var idx [16]int
	for i, p := range block {
		idx[i] = nearestIndex(p, pal[:])
	}
	return append(out, packColors(c0, c1, idx)...)
}

// encodeDXT5Block: interpolated alpha endpoints + indices + 4-color block.
func encodeDXT5Block(block [16]color.NRGBA) []byte {
	out := make([]byte, 0, 16)
	out = append(out, encodeAlphaInterp(block)...)
	e0, e1 := pickEndpoints(block, false)
	if e0 < e1 {
		e0, e1 = e1, e0
	}
	c0, c1 := e0, e1
	pal := palette(c0, c1, true)
	var idx [16]int
	for i, p := range block {
		idx[i] = nearestIndex(p, pal[:])
	}
	return append(out, packColors(c0, c1, idx)...)
}

// encodeAlpha4 writes DXT3's explicit 4-bit alpha (low nibble first,
// values scaled ×17 on read-back — rounding keeps error ≤ 8).
func encodeAlpha4(block [16]color.NRGBA) []byte {
	out := make([]byte, 8)
	for i, p := range block {
		v := uint8((uint32(p.A)*15 + 127) / 255)
		if i%2 == 0 {
			out[i/2] |= v
		} else {
			out[i/2] |= v << 4
		}
	}
	return out
}

// encodeAlphaInterp writes DXT5's alpha: max/min endpoints (decoder
// builds the same 8-entry table) + 3-bit indices packed little-endian.
func encodeAlphaInterp(block [16]color.NRGBA) []byte {
	var a0, a1 uint8
	for i, p := range block {
		if i == 0 || p.A > a0 {
			a0 = p.A
		}
		if i == 0 || p.A < a1 {
			a1 = p.A
		}
	}
	var tbl [8]byte
	tbl[0], tbl[1] = a0, a1
	if a0 > a1 {
		for i := 1; i <= 6; i++ {
			tbl[i+1] = byte(((7-i)*int(a0) + i*int(a1)) / 7)
		}
	} else {
		for i := 1; i <= 4; i++ {
			tbl[i+1] = byte(((5-i)*int(a0) + i*int(a1)) / 5)
		}
		tbl[6], tbl[7] = 0, 255
	}
	var bits uint64
	for i, p := range block {
		best, bestD := 0, -1
		for j, t := range tbl {
			d := int(p.A) - int(t)
			if d < 0 {
				d = -d
			}
			if bestD < 0 || d < bestD {
				best, bestD = j, d
			}
		}
		bits |= uint64(best&7) << (3 * i)
	}
	out := make([]byte, 8)
	out[0], out[1] = a0, a1
	for i := 0; i < 6; i++ {
		out[2+i] = uint8(bits >> (8 * i))
	}
	return out
}

// buildHeader assembles the canonical 128-byte DDS header — every field
// reskit's parse() reads (height[12:16], width[16:20], pfFlags[80:84],
// fourcc[84:88], bits[88:92], masks[92:108]) plus standard flags.
func buildHeader(w, h int, format domain.TextureFormat, mipCount, level0 int) []byte {
	hdr := make([]byte, ddsHeaderSize)
	copy(hdr[0:4], "DDS ")
	binary.LittleEndian.PutUint32(hdr[4:8], 124)

	const (
		ddsdCaps        = 0x1
		ddsdHeight      = 0x2
		ddsdWidth       = 0x4
		ddsdPitch       = 0x8
		ddsdPixelFormat = 0x1000
		ddsdMipmapcount = 0x20000
		ddsdLinearsize  = 0x80000
		ddpfFourcc      = 0x4
		ddpfRgb         = 0x40
		ddpfAlphapixels = 0x1
		ddscapsComplex  = 0x8
		ddscapsTexture  = 0x1000
		ddscapsMipmap   = 0x400000
	)

	binary.LittleEndian.PutUint32(hdr[12:16], uint32(h))
	binary.LittleEndian.PutUint32(hdr[16:20], uint32(w))
	binary.LittleEndian.PutUint32(hdr[28:32], uint32(mipCount))
	binary.LittleEndian.PutUint32(hdr[76:80], 32) // pixel format block size

	caps := uint32(ddscapsTexture)
	if mipCount > 1 {
		caps |= ddscapsComplex | ddscapsMipmap
	}
	binary.LittleEndian.PutUint32(hdr[108:112], caps)

	flags := uint32(ddsdCaps | ddsdHeight | ddsdWidth | ddsdPixelFormat)
	if mipCount > 1 {
		flags |= ddsdMipmapcount
	}

	switch format {
	case domain.FmtDXT1, domain.FmtDXT3, domain.FmtDXT5:
		binary.LittleEndian.PutUint32(hdr[8:12], flags|ddsdLinearsize)
		binary.LittleEndian.PutUint32(hdr[20:24], uint32(level0))
		binary.LittleEndian.PutUint32(hdr[80:84], ddpfFourcc)
		copy(hdr[84:88], format.String()) // "DXT1"/"DXT3"/"DXT5"
	case domain.FmtRGB24:
		binary.LittleEndian.PutUint32(hdr[8:12], flags|ddsdPitch)
		binary.LittleEndian.PutUint32(hdr[20:24], uint32(w*3))
		binary.LittleEndian.PutUint32(hdr[80:84], ddpfRgb)
		binary.LittleEndian.PutUint32(hdr[88:92], 24)
		binary.LittleEndian.PutUint32(hdr[92:96], 0xff0000)
		binary.LittleEndian.PutUint32(hdr[96:100], 0xff00)
		binary.LittleEndian.PutUint32(hdr[100:104], 0xff)
	case domain.FmtRGBA32:
		binary.LittleEndian.PutUint32(hdr[8:12], flags|ddsdPitch)
		binary.LittleEndian.PutUint32(hdr[20:24], uint32(w*4))
		binary.LittleEndian.PutUint32(hdr[80:84], ddpfRgb|ddpfAlphapixels)
		binary.LittleEndian.PutUint32(hdr[88:92], 32)
		binary.LittleEndian.PutUint32(hdr[92:96], 0xff0000)
		binary.LittleEndian.PutUint32(hdr[96:100], 0xff00)
		binary.LittleEndian.PutUint32(hdr[100:104], 0xff)
		binary.LittleEndian.PutUint32(hdr[104:108], 0xff000000)
	}
	return hdr
}
